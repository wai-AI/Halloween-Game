import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const chunks=[];
for (const name of ['story.js','engine.js','app.js']) {
  const source=await readFile(new URL('site/'+name,root),'utf8');
  chunks.push(`// ${name}\n`+source.replace(/^import .+;\r?\n/gm,'').replace(/^export /gm,''));
}
await writeFile(new URL('site/game.js',root),'// Generated by npm run build. Edit story.js, engine.js and app.js.\n(()=>{\n\'use strict\';\n'+chunks.join('\n')+'\n})();\n');
console.log('Built site/game.js (no dependencies).');
